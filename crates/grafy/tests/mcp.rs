// Test that the pipeline produces a valid index that the store can read.
#[test]
fn smoke_index_produces_readable_store() {
    use grafy::store::{Store, NODES_TABLE};
    use redb::ReadableTableMetadata;

    let dir = tempdir().unwrap();
    std::fs::write(dir.path().join("main.rs"), "fn main() {}").unwrap();

    grafy::pipeline::Pipeline::new(dir.path())
        .index()
        .expect("index should succeed");

    let store = Store::open(dir.path()).expect("store open after index");
    let db = store.read_db();
    let tx = db.begin_read().expect("begin read");
    let tbl = tx.open_table(NODES_TABLE).expect("open nodes table");
    let count = tbl.len().expect("table len");
    assert!(count >= 1, "expected at least 1 node after indexing main.rs");
}

// Test that search_graph returns structured JSON with required keys.
// Exercises the store read path used by the MCP tool.
#[test]
fn smoke_search_graph_store_path() {
    use grafy::store::{NodeKind, NodeRecord, Store, NODES_TABLE};
    use redb::ReadableTable;

    let dir = make_indexed_dir();
    let store = Store::open(dir.path()).expect("store open");
    let db = store.read_db();
    let tx = db.begin_read().expect("begin read");
    let tbl = tx.open_table(NODES_TABLE).expect("open nodes table");

    let mut functions = 0u64;
    for item in tbl.iter().expect("iter") {
        let (_, v) = item.expect("item");
        if let Ok(rec) = postcard::from_bytes::<NodeRecord>(v.value()) {
            if rec.kind == NodeKind::Function {
                functions += 1;
            }
        }
    }
    // process_order and validate_order should be indexed
    assert!(
        functions >= 1,
        "expected at least 1 Function node, got {functions}"
    );
}

