#[test]
fn parity_schema_files_exist() {
    const SCHEMA_NAMES: &[&str] = &[
        "index_repository",
        "search_graph",
        "query_graph",
        "trace_path",
        "get_code_snippet",
        "get_graph_schema",
        "get_architecture",
        "search_code",
        "list_projects",
        "delete_project",
        "index_status",
        "detect_changes",
        "manage_adr",
        "ingest_traces",
    ];

    // Locate the workspace root relative to the manifest dir
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let workspace_root = manifest_dir
        .parent()
        .and_then(|p| p.parent())
        .expect("expected crates/grafy/ layout");
    let schema_dir = workspace_root.join("tests").join("parity").join("schemas");

    for name in SCHEMA_NAMES {
        let path = schema_dir.join(format!("{name}.json"));
        assert!(
            path.exists(),
            "missing schema file: tests/parity/schemas/{name}.json"
        );
        // Verify it's valid JSON
        let content = std::fs::read_to_string(&path)
            .unwrap_or_else(|_| panic!("failed to read {}", path.display()));
        let _: serde_json::Value = serde_json::from_str(&content)
            .unwrap_or_else(|e| panic!("invalid JSON in {name}.json: {e}"));
    }
}
